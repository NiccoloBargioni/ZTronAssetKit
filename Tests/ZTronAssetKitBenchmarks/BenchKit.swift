extension ZTronAssetKitBenchmarks {
    /// P-1, P-8, P-9 and P-12 (WP-G), release configuration. Every threshold comes from `QualityBudgets`. The facade
    /// runs over a real store and engine on `FakeFileSystem` (which records the calling thread of every call) and
    /// `FakeRemoteSource`; the clock is `LiveTimeSource`, so the store's commit windows pass in real time (benchmarks are
    /// exempt from the deterministic suite's no-sleep rule, sync-2 S2-14).
    @Suite("KitBenchmarks")
    struct KitBenchmarks {
        /// A client over fakes and the live clock, with live dispatch executors (the blocking units run off the
        /// cooperative pool, as in production).
        @available(macOS 15.0, iOS 18.0, *)
        struct Fixture {
            let fileSystem: FakeFileSystem
            let source: FakeRemoteSource
            let client: AssetClient

            init(tuning: SyncTuning = SyncTuning()) {
                let time = LiveTimeSource()
                let fileSystem = FakeFileSystem(time: time)
                let source = FakeRemoteSource()
                let environment = AssetEnvironment(
                    fileSystem: fileSystem,
                    metadataExecutor: DispatchBlockingExecutor(label: "bench.kit.metadata"),
                    bulkExecutor: DispatchBlockingExecutor(label: "bench.kit.bulk"),
                    time: time,
                    random: SeededRandom(seed: 0xB17),
                    conditions: FakeDeviceConditionsSource(),
                    remoteSources: FakeRemoteSourceFactory(source: source),
                    appVersion: FakeAppVersionSource(),
                    legacyDefaults: FakeLegacyDefaults(),
                    memoryPressure: FakeMemoryPressureSource()
                )
                self.fileSystem = fileSystem
                self.source = source
                self.client = AssetClient(
                    configuration: AssetClientConfiguration(
                        remote: RemoteConfiguration(),
                        legacy: LegacyMigrationPolicy(enabled: false),
                        tuning: tuning
                    ),
                    environment: environment
                )
            }

            /// Serves `entries` (each staging `byteCount` generated bytes) and starts the client, returning once the
            /// launch run finished.
            func startHolding(_ entries: [(ManifestEntry, seed: UInt64, byteCount: Int64)]) async throws {
                let manifest = try JSONEncoder().encode(entries.map(\.0))
                await self.source.scriptManifest([.fetched(manifest, etag: ETag(rawValue: "\"bench\""))])
                for (entry, seed, byteCount) in entries {
                    await self.source.script(entry.transferID, [.stageGenerated(seed: seed, byteCount: byteCount)])
                }
                try await self.client.start()
                // Joins the launch run while it lasts; answers at once once it has finished.
                _ = await self.client.sync(.ifDue)
            }
        }

        /// An entry whose bytes are `GeneratedPayload(seed, byteCount)`.
        static func entry(_ id: String, seed: UInt64, byteCount: Int64, policy: AssetPolicy = .standard) -> (ManifestEntry, seed: UInt64, byteCount: Int64) {
            let entry = ManifestEntry(
                identifier: AssetID(id),
                fileExtension: "png",
                remotePath: "bench/\(id).png",
                localPathComponents: ["bench"],
                byteSize: byteCount,
                checksum: GeneratedPayload.sha256(seed: seed, byteCount: byteCount),
                policy: policy
            )
            return (entry, seed, byteCount)
        }

        /// A snapshot of `count` present assets (what a 10,000-asset store installs in the mirror).
        static func snapshot(count: Int) -> AssetSnapshot {
            var entries: [AssetID: SnapshotEntry] = [:]
            entries.reserveCapacity(count)
            for index in 0..<count {
                let id = AssetID("asset-\(index)")
                let location = AssetLocation(
                    id: id,
                    url: URL(fileURLWithPath: "/bench/blobs/\(index).png"),
                    fileExtension: AssetFileExtension("png")!,
                    byteSize: 1_024,
                    integrity: .verified,
                    isStale: false
                )
                entries[id] = SnapshotEntry(location: location, essential: false)
            }
            return AssetSnapshot(key: SnapshotKey(epoch: 1, version: 1), indexGeneration: 1, entries: entries)
        }

        /// The `fraction` quantile of `samples` (nearest rank).
        static func quantile(_ samples: [Double], _ fraction: Double) -> Double {
            let sorted = samples.sorted()
            guard !sorted.isEmpty else {
                return 0
            }
            let rank = min(sorted.count - 1, max(0, Int((fraction * Double(sorted.count)).rounded(.up)) - 1))
            return sorted[rank]
        }

        static func microseconds(_ duration: Duration) -> Double {
            let components = duration.components
            return Double(components.seconds) * 1_000_000 + Double(components.attoseconds) / 1_000_000_000_000
        }

        /// Warm lookups on the main actor: per-call p99 at `count` assets, over seeded random ids (hits and misses).
        @MainActor
        static func lookupTimes(client: AssetClient, count: Int, calls: Int, seed: UInt64) -> (p99: Double, median: Double) {
            var generator = SplitMix(seed: seed)
            let ids = (0..<calls).map { _ in AssetID("asset-\(Int(generator.next() % UInt64(count + count / 10 + 1)))") }
            for id in ids.prefix(1_000) {
                _ = client.lookup(id, extensions: ["png"])
            }
            let clock = ContinuousClock()
            var samples: [Double] = []
            samples.reserveCapacity(calls)
            for id in ids {
                let start = clock.now
                let location = client.lookup(id, extensions: ["png"])
                samples.append(KitBenchmarks.microseconds(clock.now - start))
                _ = location
            }
            return (KitBenchmarks.quantile(samples, 0.99), KitBenchmarks.quantile(samples, 0.5))
        }

        @available(macOS 15.0, iOS 18.0, *)
        @Test("P-1: lookup on the main actor stays under lookup_p99_us at 10,000 assets and scales within scale_ratio_max", .timeLimit(.minutes(1)))
        func lookupBudget() async throws {
            let budgets = try QualityBudgets()
            let p99Max = try #require(budgets.value("P-1", "lookup_p99_us"))
            let ratioMax = try #require(budgets.value("P-1", "scale_ratio_max"))
            var results: [Int: (p99: Double, median: Double)] = [:]
            for count in [100, 10_000] {
                let fixture = Fixture()
                let snapshot = KitBenchmarks.snapshot(count: count)
                let client = fixture.client
                results[count] = await MainActor.run {
                    _ = client.mirror.install(snapshot)
                    return KitBenchmarks.lookupTimes(client: client, count: count, calls: 20_000, seed: 0xB1)
                }
                await client.shutdown()
            }
            let small = try #require(results[100])
            let large = try #require(results[10_000])
            let ratio = large.p99 / max(small.p99, 0.001)
            print("P-1 lookup p99 \(large.p99) µs at 10,000 (median \(large.median)), \(small.p99) µs at 100; ratio \(ratio) (max \(ratioMax)); budget \(p99Max) µs")
            #expect(large.p99 <= p99Max)
            #expect(ratio <= ratioMax)
        }

        @available(macOS 15.0, iOS 18.0, *)
        @Test("P-8: UI-facing calls make zero main-thread file-system calls and each stays within ui_call_ms_max", .timeLimit(.minutes(1)))
        func uiCallsBudget() async throws {
            let budgets = try QualityBudgets()
            let mainCallsMax = Int(try #require(budgets.value("P-8", "main_thread_fs_calls_max")))
            let callMax = try #require(budgets.value("P-8", "ui_call_ms_max"))
            let fixture = Fixture()
            let present = (0..<8).map { KitBenchmarks.entry("p\($0)", seed: 800 + UInt64($0), byteCount: 4_096) }
            let onDemand = (0..<8).map { KitBenchmarks.entry("od\($0)", seed: 900 + UInt64($0), byteCount: 4_096, policy: .onDemand) }
            try await fixture.startHolding(present + onDemand)
            let client = fixture.client
            let ids = (present + onDemand).map(\.0.identifier)
            let chain = AssetFallbackChain(client: client, bundle: MainBundleLookup())
            await chain.prepare(kinds: [.image])
            let controller = PrefetchWindowController(client: client, radius: 2)
            let cache = await MainActor.run { BenchCache() }
            let rounds = 200
            let (samples, handles, resolves) = await MainActor.run { () -> ([String: [Double]], [PrefetchHandle], [Task<URL, any Error>]) in
                let clock = ContinuousClock()
                var samples: [String: [Double]] = [:]
                var handles: [PrefetchHandle] = []
                var resolves: [Task<URL, any Error>] = []
                func time(_ name: String, _ body: () -> Void) {
                    let start = clock.now
                    body()
                    samples[name, default: []].append(KitBenchmarks.microseconds(clock.now - start) / 1_000)
                }
                for round in 0..<rounds {
                    let id = ids[round % ids.count]
                    time("lookup") { _ = client.lookup(id) }
                    time("locate") { _ = chain.locate(id, kind: .image) }
                    time("prefetch") { handles.append(client.prefetch([id])) }
                    time("events") { _ = client.events }
                    time("resolve entry") {
                        resolves.append(Task { @MainActor in try await client.resolve(present[round % present.count].0.identifier) })
                    }
                    time("window update") { controller.update(ids: ids, current: round % ids.count) }
                    time("register") { try? client.register(cache) }
                    time("unregister") { client.unregister(cache) }
                }
                return (samples, handles, resolves)
            }
            for resolve in resolves {
                _ = try await resolve.value
            }
            for handle in handles {
                handle.cancel()
            }
            await MainActor.run {
                controller.cancelAll()
            }
            await client.shutdown()
            let mainCalls = fixture.fileSystem.mainThreadCalls
            print("P-8 main-thread file-system calls \(mainCalls) (max \(mainCallsMax))")
            #expect(mainCalls <= mainCallsMax)
            for (name, values) in samples.sorted(by: { $0.key < $1.key }) {
                let p99 = KitBenchmarks.quantile(values, 0.99)
                print("P-8 \(name): p99 \(p99) ms, max \(values.max() ?? 0) ms (budget \(callMax) ms)")
                #expect(p99 <= callMax, "\(name) p99 \(p99) ms")
            }
        }

        @available(macOS 15.0, iOS 18.0, *)
        @Test("P-8: the fallback chain's bundle step does no work on the main thread", .timeLimit(.minutes(1)))
        func bundleStepOffMain() async throws {
            let budgets = try QualityBudgets()
            let callMax = try #require(budgets.value("P-8", "ui_call_ms_max"))
            let fixture = Fixture()
            let bundle = ThreadRecordingBundle()
            let chain = AssetFallbackChain(client: fixture.client, bundle: bundle)
            // Called from the main actor, as a page would: the enumeration still runs in one unit on the bulk executor.
            await Task { @MainActor in
                await chain.prepare(kinds: [.image, .svg, .audio, .video(fileExtension: "mp4")])
            }.value
            let elapsed = await MainActor.run { () -> Double in
                let clock = ContinuousClock()
                let start = clock.now
                for index in 0..<1_000 {
                    _ = chain.locate(AssetID("missing-\(index)"), kind: .image)
                }
                return KitBenchmarks.microseconds(clock.now - start) / 1_000 / 1_000
            }
            print("P-8 bundle enumerations \(bundle.calls) (on main: \(bundle.calls.filter { $0 }.count)); locate \(elapsed) ms per call (budget \(callMax) ms)")
            #expect(bundle.calls == [false], "one enumeration, off the main thread")
            #expect(elapsed <= callMax)
            await fixture.client.shutdown()
        }

        @available(macOS 15.0, iOS 18.0, *)
        @Test("P-9: 64 concurrent resolves plus hashing keep the heartbeat gap p99 within budget", .timeLimit(.minutes(1)))
        func heartbeatUnderResolves() async throws {
            let budgets = try QualityBudgets()
            let tick = try #require(budgets.value("P-9", "heartbeat_tick_ms"))
            let gapMax = try #require(budgets.value("P-9", "heartbeat_gap_ms_p99_max"))
            let resolves = Int(try #require(budgets.value("P-9", "concurrent_resolves")))
            let fixture = Fixture(tuning: SyncTuning(maxConcurrentTransfers: 16))
            let entries = (0..<resolves).map { KitBenchmarks.entry("r\($0)", seed: 9_000 + UInt64($0), byteCount: 2 << 20, policy: .onDemand) }
            let manifest = try JSONEncoder().encode(entries.map(\.0))
            await fixture.source.scriptManifest([.fetched(manifest, etag: ETag(rawValue: "\"p9\""))])
            for (entry, seed, byteCount) in entries {
                await fixture.source.script(entry.transferID, [.stageGenerated(seed: seed, byteCount: byteCount)])
            }
            let client = fixture.client
            try await client.start()
            let heartbeat = Heartbeat(tickMilliseconds: tick)
            let beating = Task {
                await heartbeat.run()
            }
            let started = ContinuousClock.now
            try await withThrowingTaskGroup(of: URL.self) { group in
                for (entry, _, _) in entries {
                    group.addTask {
                        try await client.resolve(entry.identifier)
                    }
                }
                for try await _ in group {}
            }
            let elapsed = ContinuousClock.now - started
            beating.cancel()
            let gaps = await beating.value
            await client.shutdown()
            let p99 = KitBenchmarks.quantile(gaps, 0.99)
            print("P-9 \(resolves) resolves of 2 MiB in \(elapsed); heartbeat gaps \(gaps.count), p99 \(p99) ms, max \(gaps.max() ?? 0) ms (budget \(gapMax) ms, tick \(tick) ms)")
            #expect(gaps.count >= 5, "the heartbeat ticked during the resolves")
            #expect(p99 <= gapMax)
        }

        @available(macOS 15.0, iOS 18.0, *)
        @Test("P-12: AssetClient.init completes within init_ms_max and performs no file-system call", .timeLimit(.minutes(1)))
        func initBudget() async throws {
            let budgets = try QualityBudgets()
            let initMax = try #require(budgets.value("P-12", "init_ms_max"))
            let configuration = AssetClientConfiguration(remote: RemoteConfiguration(), location: .caches)
            let time = LiveTimeSource()
            let fileSystem = FakeFileSystem(time: time)
            let environment = AssetEnvironment(
                fileSystem: fileSystem,
                metadataExecutor: InlineBlockingExecutor(),
                bulkExecutor: InlineBlockingExecutor(),
                time: time,
                random: SeededRandom(seed: 12),
                conditions: FakeDeviceConditionsSource(),
                remoteSources: FakeRemoteSourceFactory(source: FakeRemoteSource()),
                appVersion: FakeAppVersionSource(),
                legacyDefaults: FakeLegacyDefaults()
            )
            let clock = ContinuousClock()
            var fakes: [Double] = []
            var live: [Double] = []
            var clients: [AssetClient] = []
            clients.append(AssetClient(configuration: configuration, environment: environment))
            clients.append(AssetClient(configuration: configuration))
            for _ in 0..<100 {
                let start = clock.now
                let client = AssetClient(configuration: configuration, environment: environment)
                fakes.append(KitBenchmarks.microseconds(clock.now - start) / 1_000)
                clients.append(client)
                let liveStart = clock.now
                let liveClient = AssetClient(configuration: configuration)
                live.append(KitBenchmarks.microseconds(clock.now - liveStart) / 1_000)
                clients.append(liveClient)
            }
            for client in clients {
                await client.shutdown()
            }
            let fakeP99 = KitBenchmarks.quantile(fakes, 0.99)
            let liveP99 = KitBenchmarks.quantile(live, 0.99)
            print("P-12 init p99 \(fakeP99) ms over fakes, \(liveP99) ms over .live() (budget \(initMax) ms); file-system calls \(fileSystem.operations.count)")
            #expect(fileSystem.operations.isEmpty, "init and an unstarted shutdown touch no file")
            #expect(fakeP99 <= initMax)
            #expect(liveP99 <= initMax)
        }
    }
}

/// A seeded 64-bit generator for benchmark inputs (SplitMix64).
struct SplitMix {
    private var state: UInt64

    init(seed: UInt64) {
        self.state = seed
    }

    mutating func next() -> UInt64 {
        self.state &+= 0x9E37_79B9_7F4A_7C15
        var value = self.state
        value = (value ^ (value >> 30)) &* 0xBF58_476D_1CE4_E5B9
        value = (value ^ (value >> 27)) &* 0x94D0_49BB_1331_11EB
        return value ^ (value >> 31)
    }
}

/// A purgeable cache that does nothing (P-8 measures registration only).
@MainActor
final class BenchCache: PurgeableCache {
    func purge(level: MemoryPressureLevel) {}
}

/// A bundle step over the live bundle that records, per enumeration, whether it ran on the main thread.
@available(macOS 15.0, iOS 18.0, *)
final class ThreadRecordingBundle: BundleLookup {
    private let recorded = Mutex<[Bool]>([])

    var calls: [Bool] {
        self.recorded.withLock { $0 }
    }

    func resources(withExtensions extensions: Set<String>) -> [BundleResourceKey: URL] {
        let isMain = Thread.isMainThread
        self.recorded.withLock { $0.append(isMain) }
        return MainBundleLookup().resources(withExtensions: extensions)
    }
}

/// A cooperative-pool task that ticks every `tickMilliseconds` on the live clock and records the gaps between ticks
/// (P-9, sync-2 S2-14).
struct Heartbeat: Sendable {
    let tickMilliseconds: Double

    /// Ticks until cancelled; returns the gaps in milliseconds.
    func run() async -> [Double] {
        let time = LiveTimeSource()
        var gaps: [Double] = []
        var last = time.monotonicNow()
        while !Task.isCancelled {
            do {
                try await time.sleep(until: last.adding(seconds: self.tickMilliseconds / 1_000))
            } catch {
                break
            }
            let now = time.monotonicNow()
            gaps.append(Double(now.nanoseconds - last.nanoseconds) / 1_000_000)
            last = now
        }
        return gaps
    }
}
